"""Map sampled byte-level BPE tokens to decoded text without re-tokenizing them.
A sampled BPE sequence need not be the tokenizer's canonical encoding of its text.
Invalid UTF-8 generated by the model is explicitly counted; the reconstruction
must exactly match the tokenizer's displayed text or evaluation fails.
"""
from bisect import bisect_left, bisect_right
from transformers.models.gpt2.tokenization_gpt2 import bytes_to_unicode


def utf8_char_spans(data):
    chars=[];spans=[];invalid=0;i=0
    while i<len(data):
        first=data[i]
        if first<0x80:
            chars.append(chr(first));spans.append((i,i+1));i+=1;continue
        width=2 if 0xC2<=first<=0xDF else 3 if 0xE0<=first<=0xEF else 4 if 0xF0<=first<=0xF4 else 0
        valid=1
        if width:
            for j in range(1,width):
                if i+j>=len(data):break
                value=data[i+j]
                low,high=0x80,0xBF
                if j==1:
                    if first==0xE0:low=0xA0
                    elif first==0xED:high=0x9F
                    elif first==0xF0:low=0x90
                    elif first==0xF4:high=0x8F
                if not low<=value<=high:break
                valid+=1
        if width and valid==width:
            chars.append(data[i:i+width].decode('utf-8'));spans.append((i,i+width));i+=width
        else:
            chars.append('\ufffd');spans.append((i,i+valid));i+=valid;invalid+=1
    text=''.join(chars)
    assert text==data.decode('utf-8',errors='replace'), 'UTF-8 span reconstruction mismatch'
    return text,spans,invalid


def original_token_offsets(tokenizer,ids,text):
    decoder={v:k for k,v in bytes_to_unicode().items()}
    tokens=tokenizer.convert_ids_to_tokens(ids)
    pieces=[bytes(decoder[ch] for ch in token) for token in tokens]
    blob=b''.join(pieces)
    reconstructed,chars,invalid=utf8_char_spans(blob)
    if reconstructed!=text:
        raise ValueError('Generated token bytes do not reconstruct displayed text exactly')
    starts=[a for a,b in chars];ends=[b for a,b in chars]
    offsets=[];cursor=0
    for piece in pieces:
        stop=cursor+len(piece)
        offsets.append((bisect_right(ends,cursor),bisect_left(starts,stop)))
        cursor=stop
    assert len(offsets)==len(ids)
    return offsets,invalid


def sentence_assignment(offsets,spans):
    """Assign each token once, by maximum character overlap (ties: earlier sentence).
    Whitespace-only gap tokens belong to the following sentence, or the final one.
    """
    groups=[[] for _ in spans]
    if not spans:
        if offsets:raise ValueError('Nonempty tokens but no sentence span')
        return groups
    for i,(a,b) in enumerate(offsets):
        overlaps=[max(0,min(b,end)-max(a,start)) for start,end in spans]
        if max(overlaps)>0:
            j=max(range(len(spans)),key=lambda idx:overlaps[idx])
        else:
            j=next((idx for idx,(start,end) in enumerate(spans) if start>=b),len(spans)-1)
        groups[j].append(i)
    assert sorted(i for g in groups for i in g)==list(range(len(offsets)))
    return groups
